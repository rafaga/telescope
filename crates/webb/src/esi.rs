/// Network boundary towards the CCP servers (SSO + ESI).
///
/// Every operation that talks to CCP goes through this trait so the
/// application logic in [`EsiManagerCore`] can be unit tested without
/// network access using the `MockEsiApi` generated by mockall in test
/// builds. The production implementation is [`LiveEsiApi`].
#[cfg_attr(test, mockall::automock)]
#[allow(async_fn_in_trait)]
pub trait EsiApi: Send {
    /// Builds the SSO authorization URL (and PKCE verifier when the
    /// `native-auth-flow` feature is enabled). Pure, no network involved.
    fn authorize_url(&self) -> Result<AuthorizeInfo, String>;
    /// Whether the underlying client holds a complete token set.
    fn has_token_state(&self) -> bool;
    /// Returns the current token set, if complete.
    fn current_tokens(&self) -> Option<TokenSet>;
    /// Exchanges an OAuth code for tokens and returns the JWT claims.
    async fn authenticate(
        &mut self,
        code: &str,
        verifier: Option<String>,
    ) -> Result<Option<AuthClaims>, String>;
    /// Refreshes the OAuth metadata document from the SSO server.
    async fn update_spec(&mut self) -> Result<(), String>;
    /// Exchanges a refresh token for a new token set.
    async fn refresh_access_token(&mut self, refresh_token: &str) -> Result<TokenSet, String>;
    /// Fetches the public info of a character from ESI.
    async fn get_character_public_info(
        &mut self,
        character_id: i32,
    ) -> Result<CharacterPublicInfo, String>;
    /// Fetches the public info of a corporation from ESI.
    async fn get_corporation_public_info(
        &mut self,
        corporation_id: i32,
    ) -> Result<Corporation, String>;
    /// Fetches the info of an alliance from ESI.
    async fn get_alliance_info(&mut self, alliance_id: i32) -> Result<Alliance, String>;
    /// Fetches the URL of the 128x128 character portrait from ESI.
    async fn get_character_portrait_url(&mut self, character_id: i32) -> Result<String, String>;
    /// Fetches the current solar system of a character from ESI.
    async fn get_location(&mut self, character_id: i32) -> Result<i32, String>;
}

/// Production [`EsiApi`] implementation backed by `rfesi`.
#[derive(Clone)]
pub struct LiveEsiApi {
    esi: Esi,
}

impl EsiApi for LiveEsiApi {
    fn authorize_url(&self) -> Result<AuthorizeInfo, String> {
        self.esi
            .get_authorize_url()
            .map(|info| AuthorizeInfo {
                url: info.authorization_url,
                pkce_verifier: info.pkce_verifier,
            })
            .map_err(|e| e.to_string())
    }

    fn has_token_state(&self) -> bool {
        self.esi.access_expiration.is_some()
            && self.esi.access_token.is_some()
            && self.esi.refresh_token.is_some()
    }

    fn current_tokens(&self) -> Option<TokenSet> {
        Some(TokenSet {
            token: self.esi.access_token.clone()?,
            refresh_token: self.esi.refresh_token.clone()?,
            expiration: chrono::DateTime::from_timestamp_millis(self.esi.access_expiration?),
        })
    }

    async fn authenticate(
        &mut self,
        code: &str,
        verifier: Option<String>,
    ) -> Result<Option<AuthClaims>, String> {
        match self.esi.authenticate(code, verifier).await {
            Ok(Some(claims)) => Ok(Some(AuthClaims {
                name: claims.name,
                sub: claims.sub,
            })),
            Ok(None) => Ok(None),
            Err(t_error) => Err(t_error.to_string()),
        }
    }

    async fn update_spec(&mut self) -> Result<(), String> {
        self.esi
            .update_spec()
            .await
            .map_err(|t_error| t_error.to_string())
    }

    async fn refresh_access_token(&mut self, refresh_token: &str) -> Result<TokenSet, String> {
        self.esi
            .refresh_access_token(Some(refresh_token))
            .await
            .map_err(|t_error| t_error.to_string())?;
        self.current_tokens()
            .ok_or_else(|| String::from("incomplete token state after refresh"))
    }

    async fn get_character_public_info(
        &mut self,
        character_id: i32,
    ) -> Result<CharacterPublicInfo, String> {
        self.esi
            .group_character()
            .get_public_info(character_id)
            .await
            .map(|info| CharacterPublicInfo {
                corporation_id: info.corporation_id,
                alliance_id: info.alliance_id,
            })
            .map_err(|t_error| t_error.to_string())
    }

    async fn get_corporation_public_info(
        &mut self,
        corporation_id: i32,
    ) -> Result<Corporation, String> {
        self.esi
            .group_corporation()
            .get_public_info(corporation_id)
            .await
            .map(|info| Corporation {
                id: corporation_id,
                name: info.name,
            })
            .map_err(|t_error| t_error.to_string())
    }

    async fn get_alliance_info(&mut self, alliance_id: i32) -> Result<Alliance, String> {
        self.esi
            .group_alliance()
            .get_info(alliance_id)
            .await
            .map(|info| Alliance {
                id: alliance_id,
                name: info.name,
            })
            .map_err(|t_error| t_error.to_string())
    }

    async fn get_character_portrait_url(&mut self, character_id: i32) -> Result<String, String> {
        self.esi
            .group_character()
            .get_portrait(character_id)
            .await
            .map_err(|t_error| t_error.to_string())?
            .px128x128
            .ok_or_else(|| String::from("no 128x128 portrait available"))
    }

    async fn get_location(&mut self, character_id: i32) -> Result<i32, String> {
        self.esi
            .group_location()
            .get_location(character_id)
            .await
            .map(|location| location.solar_system_id)
            .map_err(|t_error| t_error.to_string())
    }
}

